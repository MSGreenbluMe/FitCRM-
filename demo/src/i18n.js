// Lightweight i18n for the FitCRM demo.
// Language is stored in the trainer settings (localStorage `fitcrm-settings`,
// profile.language). Supported: en (English), sk (Slovenčina), cs (Čeština).

const SETTINGS_KEY = "fitcrm-settings";
export const SUPPORTED_LANGS = ["en", "sk", "cs"];
export const DEFAULT_LANG = "en";

function detectLang() {
  try {
    const saved = JSON.parse(localStorage.getItem(SETTINGS_KEY) || "null");
    const lang = saved?.profile?.language;
    if (lang && SUPPORTED_LANGS.includes(lang)) return lang;
  } catch (e) {
    /* ignore */
  }
  return DEFAULT_LANG;
}

let currentLang = detectLang();

export function getLang() {
  return currentLang;
}

export function setLang(lang) {
  if (SUPPORTED_LANGS.includes(lang)) currentLang = lang;
}

function interpolate(str, vars) {
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

// Translate a dotted key. Falls back to English, then to the raw key.
export function t(key, vars) {
  const dict = STRINGS[currentLang] || STRINGS[DEFAULT_LANG];
  let val = dict[key];
  if (val === undefined) val = STRINGS[DEFAULT_LANG][key];
  if (val === undefined) val = key;
  return interpolate(val, vars);
}

